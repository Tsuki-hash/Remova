let lang: Lang = "zh";

export function loadLang() {
  const v = localStorage.getItem("remova_lang");
  if (v === "en" || v === "zh") lang = v;
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  localStorage.setItem("remova_lang", l);
}

export function currentLang() {
  return lang;
}

